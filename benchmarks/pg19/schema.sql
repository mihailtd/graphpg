-- Deterministic schema and dataset for comparing PostgreSQL 18 and PostgreSQL 19 under graphpg.
-- Override table sizes with `psql -v posts=... -v authors=... -v comments=... -v categories=... -v tags=...`.
\if :{?authors} \else \set authors 1000 \endif
\if :{?posts} \else \set posts 100000 \endif
\if :{?comments} \else \set comments 225000 \endif
\if :{?categories} \else \set categories 2000 \endif
\if :{?tags} \else \set tags 5000 \endif

DROP SCHEMA IF EXISTS bench CASCADE;
CREATE SCHEMA bench;

CREATE TYPE bench.post_status AS ENUM ('draft', 'published', 'archived');

CREATE TABLE bench.authors (
    id integer PRIMARY KEY,
    username text NOT NULL UNIQUE,
    bio text
);

-- 5-level category trees for recursive ancestor queries
CREATE TABLE bench.categories (
    id integer PRIMARY KEY,
    parent_id integer REFERENCES bench.categories (id),
    name text NOT NULL
);

CREATE TABLE bench.tags (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    name text NOT NULL
);

CREATE TABLE bench.posts (
    id integer PRIMARY KEY,
    author_id integer NOT NULL REFERENCES bench.authors (id),
    category_id integer NOT NULL REFERENCES bench.categories (id),
    title text NOT NULL,
    status bench.post_status NOT NULL,
    priority integer NOT NULL,
    summary text,
    body text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE bench.comments (
    id integer PRIMARY KEY,
    post_id integer NOT NULL REFERENCES bench.posts (id),
    author_id integer NOT NULL REFERENCES bench.authors (id),
    body text NOT NULL
);

-- Target table for write / FK / connectOrCreate scenarios
CREATE TABLE bench.notes (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    author_id integer NOT NULL REFERENCES bench.authors (id),
    tag_id integer REFERENCES bench.tags (id),
    body text NOT NULL,
    hits integer NOT NULL DEFAULT 0
);

INSERT INTO bench.authors
SELECT i, 'author' || i, repeat('bio ', 10)
FROM generate_series(1, :authors) i;

INSERT INTO bench.categories
SELECT i,
       CASE WHEN i <= (:categories / 5) THEN NULL ELSE i - (:categories / 5) END,
       'Category ' || i
FROM generate_series(1, :categories) i;

INSERT INTO bench.tags (id, slug, name)
SELECT i, 'tag-' || i, 'Tag ' || i
FROM generate_series(1, :tags) i;
SELECT setval(pg_get_serial_sequence('bench.tags', 'id'), :tags);

-- `body` (~2.6 KB) triggers TOAST compression (pglz default on PG 18 vs lz4 default on PG 19).
INSERT INTO bench.posts
SELECT i,
       1 + (i % :authors),
       1 + (i % :categories),
       'Post number ' || i,
       (ARRAY['draft', 'published', 'published', 'archived'])[1 + (i % 4)]::bench.post_status,
       1 + (i % 20),
       CASE WHEN i % 3 = 0 THEN NULL ELSE 'Summary for post ' || i END,
       repeat('Lorem ipsum dolor sit amet, consectetur adipiscing elit. ', 45) || i,
       timestamptz '2026-01-01' + (i || ' minutes')::interval
FROM generate_series(1, :posts) i;

-- Every 4th post has zero comments so anti=comments matches 25% of posts.
INSERT INTO bench.comments
SELECT i,
       CASE WHEN (1 + (i % :posts)) % 4 = 0 THEN 1 + ((i + 1) % :posts) ELSE 1 + (i % :posts) END,
       1 + (i % :authors),
       'Comment ' || i
FROM generate_series(1, :comments) i;

INSERT INTO bench.notes (author_id, tag_id, body)
SELECT 1 + (i % :authors), 1 + (i % :tags), 'note ' || i
FROM generate_series(1, 1000) i;

CREATE INDEX posts_author_id ON bench.posts (author_id);
CREATE INDEX posts_category_id ON bench.posts (category_id);
CREATE INDEX posts_status_created_at ON bench.posts (status, created_at);
CREATE INDEX posts_priority ON bench.posts (priority);
CREATE INDEX comments_post_id ON bench.comments (post_id);
CREATE INDEX comments_author_id ON bench.comments (author_id);
CREATE INDEX categories_parent_id ON bench.categories (parent_id);
CREATE INDEX notes_author_id ON bench.notes (author_id);
CREATE INDEX notes_tag_id ON bench.notes (tag_id);

VACUUM ANALYZE;
CHECKPOINT;
